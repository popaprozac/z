import type {
  Expression,
  FunctionDeclaration,
  Program,
  Statement,
  StructDeclaration,
} from "./ast.ts";

type GenerationContext = {
  readonly structs: Map<string, StructDeclaration>;
  readonly functions: Map<string, FunctionDeclaration>;
  readonly localTypes: Map<string, string>;
  readonly receiver: StructDeclaration | null;
};

const primitiveTypeNames: Record<string, string> = {
  i32: "int32_t",
  void: "void",
  bool: "bool",
  cstring: "const char *",
};

export function generateC(program: Program, sourceName: string): string {
  const structs = new Map(program.structs.map((declaration) => [declaration.name, declaration]));
  const functions = new Map(program.functions.map((declaration) => [declaration.name, declaration]));
  const lines = [
    "/* Generated by the Z bootstrap compiler. */",
    `/* Source: ${sourceName.replaceAll("*/", "* /")} */`,
    "#include <stdbool.h>",
    "#include <stdint.h>",
  ];

  for (const declaration of program.imports) {
    lines.push(`#include <${declaration.header}>`);
  }
  lines.push("");

  for (const declaration of program.structs) {
    lines.push(`typedef struct ${structName(declaration.name)} ${structName(declaration.name)};`);
  }
  if (program.structs.length > 0) lines.push("");

  for (const declaration of orderedStructs(program.structs, structs)) {
    lines.push(generateStruct(declaration, structs), "");
  }

  for (const declaration of program.structs) {
    for (const method of declaration.methods) {
      lines.push(`${generateFunctionSignature(method, structs, declaration)};`);
    }
  }
  for (const declaration of program.functions) {
    lines.push(`${generateFunctionSignature(declaration, structs, null)};`);
  }
  if (program.structs.some((declaration) => declaration.methods.length > 0) || program.functions.length > 0) {
    lines.push("");
  }

  for (const declaration of program.structs) {
    for (const method of declaration.methods) {
      lines.push(generateFunction(method, structs, functions, declaration), "");
    }
  }
  for (const declaration of program.functions) {
    lines.push(generateFunction(declaration, structs, functions, null), "");
  }
  return `${lines.join("\n")}\n`;
}

function generateStruct(declaration: StructDeclaration, structs: Map<string, StructDeclaration>): string {
  const fields = declaration.fields
    .map((field) => `  ${mapType(field.type.name, structs)} ${field.name};`)
    .join("\n");
  return `struct ${structName(declaration.name)} {\n${fields}\n};`;
}

function generateFunction(
  declaration: FunctionDeclaration,
  structs: Map<string, StructDeclaration>,
  functions: Map<string, FunctionDeclaration>,
  receiver: StructDeclaration | null,
): string {
  const localTypes = new Map(declaration.parameters.map((parameter) => [parameter.name, parameter.type.name]));
  if (receiver) localTypes.set("this", receiver.name);
  const context: GenerationContext = { structs, functions, localTypes, receiver };
  const body = declaration.body.map((statement) => {
    const generated = generateStatement(statement, context);
    if (statement.kind === "variable") {
      const type = statement.type?.name ?? inferExpressionType(statement.initializer, context);
      localTypes.set(statement.name, type);
    }
    return `  ${generated}`;
  }).join("\n");
  return `${generateFunctionSignature(declaration, structs, receiver)} {\n${body}\n}`;
}

function generateFunctionSignature(
  declaration: FunctionDeclaration,
  structs: Map<string, StructDeclaration>,
  receiver: StructDeclaration | null,
): string {
  const storage = receiver || declaration.name !== "main" ? "static " : "";
  const name = receiver ? methodName(receiver.name, declaration.name) : declaration.name;
  const parameters = declaration.parameters.map(
    (parameter) => `${mapType(parameter.type.name, structs)} ${parameter.name}`,
  );
  if (receiver) parameters.unshift(`const ${structName(receiver.name)} *self`);
  return `${storage}${mapType(declaration.returnType.name, structs)} ${name}(${parameters.join(", ") || "void"})`;
}

function generateStatement(statement: Statement, context: GenerationContext): string {
  switch (statement.kind) {
    case "variable": {
      const zType = statement.type?.name ?? inferExpressionType(statement.initializer, context);
      const declaration = generateLocalDeclaration(zType, statement.name, statement.mutable, context.structs);
      return `${declaration} = ${generateExpression(statement.initializer, context)};`;
    }
    case "return":
      return statement.expression ? `return ${generateExpression(statement.expression, context)};` : "return;";
    case "expressionStatement":
      return `${generateExpression(statement.expression, context)};`;
  }
}

function generateLocalDeclaration(
  type: string,
  name: string,
  mutable: boolean,
  structs: Map<string, StructDeclaration>,
): string {
  if (type === "cstring") {
    return mutable ? `const char *${name}` : `const char * const ${name}`;
  }
  return `${mutable ? "" : "const "}${mapType(type, structs)} ${name}`;
}

function generateExpression(expression: Expression, context: GenerationContext): string {
  switch (expression.kind) {
    case "number":
      return expression.value;
    case "string":
      return JSON.stringify(expression.value);
    case "identifier":
      return expression.name === "this" ? "(*self)" : expression.name;
    case "binary":
      return `(${generateExpression(expression.left, context)} ${expression.operator} ${generateExpression(expression.right, context)})`;
    case "structExpression": {
      const fields = expression.fields
        .map((field) => `.${field.name} = ${generateExpression(field.expression, context)}`)
        .join(", ");
      return `(${structName(expression.typeName)}){ ${fields} }`;
    }
    case "member": {
      if (isForeignMember(expression, context)) return expression.property;
      if (expression.object.kind === "identifier" && expression.object.name === "this") {
        return `self->${expression.property}`;
      }
      return `(${generateExpression(expression.object, context)}).${expression.property}`;
    }
    case "call": {
      if (expression.callee.kind === "member" && !isForeignMember(expression.callee, context)) {
        const receiverType = inferExpressionType(expression.callee.object, context);
        const receiver = generateExpression(expression.callee.object, context);
        const receiverArgument = expression.callee.object.kind === "identifier" && expression.callee.object.name === "this"
          ? "self"
          : `&(${receiver})`;
        const args = [receiverArgument, ...expression.arguments.map((argument) => generateExpression(argument, context))];
        return `${methodName(receiverType, expression.callee.property)}(${args.join(", ")})`;
      }
      return `${generateExpression(expression.callee, context)}(${expression.arguments.map((argument) => generateExpression(argument, context)).join(", ")})`;
    }
  }
}

function inferExpressionType(expression: Expression, context: GenerationContext): string {
  switch (expression.kind) {
    case "number":
    case "binary":
      return "i32";
    case "string":
      return "cstring";
    case "identifier":
      return context.localTypes.get(expression.name) ?? "i32";
    case "structExpression":
      return expression.typeName;
    case "member": {
      if (isForeignMember(expression, context)) return "i32";
      const owner = context.structs.get(inferExpressionType(expression.object, context));
      return owner?.fields.find((field) => field.name === expression.property)?.type.name ?? "i32";
    }
    case "call": {
      if (expression.callee.kind === "identifier") {
        return context.functions.get(expression.callee.name)?.returnType.name ?? "i32";
      }
      if (expression.callee.kind === "member" && !isForeignMember(expression.callee, context)) {
        const owner = context.structs.get(inferExpressionType(expression.callee.object, context));
        return owner?.methods.find((method) => method.name === expression.callee.property)?.returnType.name ?? "i32";
      }
      return "i32";
    }
  }
}

function isForeignMember(
  expression: Extract<Expression, { kind: "member" }>,
  context: GenerationContext,
): boolean {
  return expression.object.kind === "identifier"
    && !context.localTypes.has(expression.object.name)
    && !context.structs.has(expression.object.name);
}

function mapType(name: string, structs: Map<string, StructDeclaration>): string {
  const primitive = primitiveTypeNames[name];
  if (primitive) return primitive;
  if (structs.has(name)) return structName(name);
  throw new Error(`unsupported bootstrap type ${JSON.stringify(name)}`);
}

function structName(name: string): string {
  return `Z_${name}`;
}

function methodName(owner: string, method: string): string {
  return `${structName(owner)}_${method}`;
}

function orderedStructs(
  declarations: StructDeclaration[],
  structs: Map<string, StructDeclaration>,
): StructDeclaration[] {
  const result: StructDeclaration[] = [];
  const visited = new Set<string>();
  const visit = (declaration: StructDeclaration): void => {
    if (visited.has(declaration.name)) return;
    visited.add(declaration.name);
    for (const field of declaration.fields) {
      const nested = structs.get(field.type.name);
      if (nested) visit(nested);
    }
    result.push(declaration);
  };
  for (const declaration of declarations) visit(declaration);
  return result;
}
