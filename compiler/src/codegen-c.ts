import type {
  Expression,
  EnumDeclaration,
  FunctionDeclaration,
  Program,
  Statement,
  StructDeclaration,
} from "./ast.ts";
import { resultTypeName } from "./results.ts";

type GenerationContext = {
  readonly structs: Map<string, StructDeclaration>;
  readonly enums: Map<string, EnumDeclaration>;
  readonly functions: Map<string, FunctionDeclaration>;
  readonly localTypes: Map<string, string>;
  readonly receiver: StructDeclaration | null;
  readonly owner: FunctionDeclaration;
  readonly matchCounter: { value: number };
};

const primitiveTypeNames: Record<string, string> = {
  i32: "int32_t",
  void: "void",
  bool: "bool",
  cstring: "const char *",
};

export function generateC(program: Program, sourceName: string): string {
  const structs = new Map(program.structs.map((declaration) => [declaration.name, declaration]));
  const enums = new Map(program.enums.map((declaration) => [declaration.name, declaration]));
  const functions = new Map(program.functions.map((declaration) => [declaration.name, declaration]));
  const lines = [
    "/* Generated by the Z bootstrap compiler. */",
    `/* Source: ${sourceName.replaceAll("*/", "* /")} */`,
    "#include <stdbool.h>",
    "#include <stdint.h>",
  ];

  for (const declaration of program.imports) {
    lines.push(`#include <${declaration.header}>`);
  }
  lines.push("");

  for (const declaration of program.structs) {
    lines.push(`typedef struct ${structName(declaration.name)} ${structName(declaration.name)};`);
  }
  for (const declaration of program.enums) {
    lines.push(`typedef struct ${enumName(declaration.name)} ${enumName(declaration.name)};`);
  }
  if (program.structs.length > 0 || program.enums.length > 0) lines.push("");

  for (const declaration of orderedStructs(program.structs, structs)) {
    lines.push(generateStruct(declaration, structs, enums), "");
  }
  for (const declaration of program.enums) {
    lines.push(generateEnum(declaration, structs, enums), "");
  }

  for (const declaration of program.structs) {
    for (const method of declaration.methods) {
      lines.push(`${generateFunctionSignature(method, structs, enums, declaration)};`);
    }
  }
  for (const declaration of program.functions) {
    lines.push(`${generateFunctionSignature(declaration, structs, enums, null)};`);
  }
  if (program.structs.some((declaration) => declaration.methods.length > 0) || program.functions.length > 0) {
    lines.push("");
  }

  for (const declaration of program.structs) {
    for (const method of declaration.methods) {
      lines.push(generateFunction(method, structs, enums, functions, declaration), "");
    }
  }
  for (const declaration of program.functions) {
    lines.push(generateFunction(declaration, structs, enums, functions, null), "");
  }
  return `${lines.join("\n")}\n`;
}

function generateStruct(declaration: StructDeclaration, structs: Map<string, StructDeclaration>, enums: Map<string, EnumDeclaration>): string {
  const fields = declaration.fields
    .map((field) => `  ${mapType(field.type.name, structs, enums)} ${field.name};`)
    .join("\n");
  return `struct ${structName(declaration.name)} {\n${fields}\n};`;
}

function generateEnum(declaration: EnumDeclaration, structs: Map<string, StructDeclaration>, enums: Map<string, EnumDeclaration>): string {
  const tag = declaration.variants.map((variant) => `  ${variantTag(declaration.name, variant.name)},`).join("\n");
  const payloads = declaration.variants.filter((variant) => variant.payload)
    .map((variant) => `    ${mapType(variant.payload!.name, structs, enums)} ${variant.name};`).join("\n");
  const union = payloads ? `\n  union {\n${payloads}\n  } data;` : "";
  return `typedef enum {\n${tag}\n} ${enumName(declaration.name)}_Tag;\n\nstruct ${enumName(declaration.name)} {\n  ${enumName(declaration.name)}_Tag tag;${union}\n};`;
}

function generateFunction(
  declaration: FunctionDeclaration,
  structs: Map<string, StructDeclaration>,
  enums: Map<string, EnumDeclaration>,
  functions: Map<string, FunctionDeclaration>,
  receiver: StructDeclaration | null,
): string {
  const localTypes = new Map(declaration.parameters.map((parameter) => [parameter.name, parameter.type.name]));
  if (receiver) localTypes.set("this", receiver.name);
  const context: GenerationContext = { structs, enums, functions, localTypes, receiver, owner: declaration, matchCounter: { value: 0 } };
  const body = declaration.body.map((statement) => {
    const generated = generateStatement(statement, context);
    if (statement.kind === "variable") {
      const type = statement.type?.name ?? inferExpressionType(statement.initializer, context);
      localTypes.set(statement.name, type);
    }
    return `  ${generated}`;
  }).join("\n");
  return `${generateFunctionSignature(declaration, structs, enums, receiver)} {\n${body}\n}`;
}

function generateFunctionSignature(
  declaration: FunctionDeclaration,
  structs: Map<string, StructDeclaration>,
  enums: Map<string, EnumDeclaration>,
  receiver: StructDeclaration | null,
): string {
  const storage = receiver || declaration.name !== "main" ? "static " : "";
  const name = receiver ? methodName(receiver.name, declaration.name) : declaration.name;
  const parameters = declaration.parameters.map(
    (parameter) => `${mapType(parameter.type.name, structs, enums)} ${parameter.name}`,
  );
  if (receiver) parameters.unshift(`const ${structName(receiver.name)} *self`);
  const returnName = declaration.errorType
    ? resultTypeName(declaration.returnType.name, declaration.errorType.name)
    : declaration.returnType.name;
  return `${storage}${mapType(returnName, structs, enums)} ${name}(${parameters.join(", ") || "void"})`;
}

function generateStatement(statement: Statement, context: GenerationContext): string {
  switch (statement.kind) {
    case "variable": {
      const zType = statement.type?.name ?? inferExpressionType(statement.initializer, context);
      const declaration = generateLocalDeclaration(zType, statement.name, statement.mutable, context.structs, context.enums);
      return `${declaration} = ${generateExpression(statement.initializer, context)};`;
    }
    case "return":
      if (!statement.expression) return "return;";
      if (context.owner.errorType) {
        const result = resultTypeName(context.owner.returnType.name, context.owner.errorType.name);
        return `return (${enumName(result)}){ .tag = ${variantTag(result, "success")}, .data.success = ${generateExpression(statement.expression, context)} };`;
      }
      return `return ${generateExpression(statement.expression, context)};`;
    case "throw": {
      const result = resultTypeName(context.owner.returnType.name, context.owner.errorType!.name);
      return `return (${enumName(result)}){ .tag = ${variantTag(result, "failure")}, .data.failure = ${generateExpression(statement.expression, context)} };`;
    }
    case "expressionStatement":
      return `${generateExpression(statement.expression, context)};`;
    case "match":
      return generateMatch(statement, context);
  }
}

function generateLocalDeclaration(
  type: string,
  name: string,
  mutable: boolean,
  structs: Map<string, StructDeclaration>,
  enums: Map<string, EnumDeclaration>,
): string {
  if (type === "cstring") {
    return mutable ? `const char *${name}` : `const char * const ${name}`;
  }
  return `${mutable ? "" : "const "}${mapType(type, structs, enums)} ${name}`;
}

function generateMatch(statement: Extract<Statement, { kind: "match" }>, context: GenerationContext): string {
  const type = inferExpressionType(statement.expression, context);
  const declaration = context.enums.get(type)!;
  const temporary = `_z_match_${context.matchCounter.value++}`;
  const subject = generateExpression(statement.expression, context);
  const arms = statement.arms.map((arm) => {
    const variant = declaration.variants.find((candidate) => candidate.name === arm.variantName)!;
    const armTypes = new Map(context.localTypes);
    const binding = variant.payload && arm.binding
      ? `\n      const ${mapType(variant.payload.name, context.structs, context.enums)} ${arm.binding} = ${temporary}.data.${variant.name};`
      : "";
    if (variant.payload && arm.binding) armTypes.set(arm.binding, variant.payload.name);
    const armContext = { ...context, localTypes: armTypes };
    const breakStatement = statementTerminates(arm.body) ? "" : "\n      break;";
    return `    case ${variantTag(type, variant.name)}: {${binding}\n      ${generateStatement(arm.body, armContext)}${breakStatement}\n    }`;
  }).join("\n");
  return `const ${enumName(type)} ${temporary} = ${subject};\n  switch (${temporary}.tag) {\n${arms}\n  }`;
}

function statementTerminates(statement: Statement): boolean {
  if (statement.kind === "return" || statement.kind === "throw") return true;
  return statement.kind === "match" && statement.arms.length > 0
    && statement.arms.every((arm) => statementTerminates(arm.body));
}

function generateExpression(expression: Expression, context: GenerationContext): string {
  switch (expression.kind) {
    case "number":
      return expression.value;
    case "string":
      return JSON.stringify(expression.value);
    case "identifier":
      return expression.name === "this" ? "(*self)" : expression.name;
    case "binary":
      return `(${generateExpression(expression.left, context)} ${expression.operator} ${generateExpression(expression.right, context)})`;
    case "structExpression": {
      const fields = expression.fields
        .map((field) => `.${field.name} = ${generateExpression(field.expression, context)}`)
        .join(", ");
      return `(${structName(expression.typeName)}){ ${fields} }`;
    }
    case "variantExpression":
      return `(${enumName(expression.enumName)}){ .tag = ${variantTag(expression.enumName, expression.variantName)}, .data.${expression.variantName} = ${generateExpression(expression.payload, context)} }`;
    case "attempt":
      return generateExpression(expression.expression, context);
    case "member": {
      if (expression.object.kind === "identifier") {
        const declaration = context.enums.get(expression.object.name);
        const variant = declaration?.variants.find((candidate) => candidate.name === expression.property);
        if (declaration && variant) {
          return `(${enumName(declaration.name)}){ .tag = ${variantTag(declaration.name, variant.name)} }`;
        }
      }
      if (isForeignMember(expression, context)) return expression.property;
      if (expression.object.kind === "identifier" && expression.object.name === "this") {
        return `self->${expression.property}`;
      }
      return `(${generateExpression(expression.object, context)}).${expression.property}`;
    }
    case "call": {
      if (expression.callee.kind === "member" && !isForeignMember(expression.callee, context)) {
        if (expression.callee.object.kind === "identifier") {
          const declaration = context.enums.get(expression.callee.object.name);
          const variant = declaration?.variants.find((candidate) => candidate.name === expression.callee.property);
          if (declaration && variant) {
            const payload = variant.payload ? `, .data.${variant.name} = ${generateExpression(expression.arguments[0], context)}` : "";
            return `(${enumName(declaration.name)}){ .tag = ${variantTag(declaration.name, variant.name)}${payload} }`;
          }
        }
        const receiverType = inferExpressionType(expression.callee.object, context);
        const receiver = generateExpression(expression.callee.object, context);
        const receiverArgument = expression.callee.object.kind === "identifier" && expression.callee.object.name === "this"
          ? "self"
          : `&(${receiver})`;
        const args = [receiverArgument, ...expression.arguments.map((argument) => generateExpression(argument, context))];
        return `${methodName(receiverType, expression.callee.property)}(${args.join(", ")})`;
      }
      return `${generateExpression(expression.callee, context)}(${expression.arguments.map((argument) => generateExpression(argument, context)).join(", ")})`;
    }
  }
}

function inferExpressionType(expression: Expression, context: GenerationContext): string {
  switch (expression.kind) {
    case "number":
    case "binary":
      return "i32";
    case "string":
      return "cstring";
    case "identifier":
      return context.localTypes.get(expression.name) ?? "i32";
    case "structExpression":
      return expression.typeName;
    case "variantExpression":
      return expression.enumName;
    case "attempt": {
      const inner = expression.expression;
      if (inner.kind === "call" && inner.callee.kind === "identifier") {
        const target = context.functions.get(inner.callee.name)!;
        return resultTypeName(target.returnType.name, target.errorType!.name);
      }
      if (inner.kind === "call" && inner.callee.kind === "member") {
        const receiver = context.structs.get(inferExpressionType(inner.callee.object, context))!;
        const method = receiver.methods.find((candidate) => candidate.name === inner.callee.property)!;
        return resultTypeName(method.returnType.name, method.errorType!.name);
      }
      return "i32";
    }
    case "member": {
      if (expression.object.kind === "identifier" && context.enums.has(expression.object.name)) {
        return expression.object.name;
      }
      if (isForeignMember(expression, context)) return "i32";
      const owner = context.structs.get(inferExpressionType(expression.object, context));
      return owner?.fields.find((field) => field.name === expression.property)?.type.name ?? "i32";
    }
    case "call": {
      if (expression.callee.kind === "identifier") {
        return context.functions.get(expression.callee.name)?.returnType.name ?? "i32";
      }
      if (expression.callee.kind === "member" && !isForeignMember(expression.callee, context)) {
        if (expression.callee.object.kind === "identifier" && context.enums.has(expression.callee.object.name)) {
          return expression.callee.object.name;
        }
        const owner = context.structs.get(inferExpressionType(expression.callee.object, context));
        return owner?.methods.find((method) => method.name === expression.callee.property)?.returnType.name ?? "i32";
      }
      return "i32";
    }
  }
}

function isForeignMember(
  expression: Extract<Expression, { kind: "member" }>,
  context: GenerationContext,
): boolean {
  return expression.object.kind === "identifier"
    && !context.localTypes.has(expression.object.name)
    && !context.structs.has(expression.object.name)
    && !context.enums.has(expression.object.name);
}

function mapType(name: string, structs: Map<string, StructDeclaration>, enums: Map<string, EnumDeclaration>): string {
  const primitive = primitiveTypeNames[name];
  if (primitive) return primitive;
  if (structs.has(name)) return structName(name);
  if (enums.has(name)) return enumName(name);
  throw new Error(`unsupported bootstrap type ${JSON.stringify(name)}`);
}

function enumName(name: string): string {
  return `Z_${name.replace(/^__z_/, "")}`;
}

function variantTag(owner: string, variant: string): string {
  return `${enumName(owner)}_${variant}`;
}

function structName(name: string): string {
  return `Z_${name}`;
}

function methodName(owner: string, method: string): string {
  return `${structName(owner)}_${method}`;
}

function orderedStructs(
  declarations: StructDeclaration[],
  structs: Map<string, StructDeclaration>,
): StructDeclaration[] {
  const result: StructDeclaration[] = [];
  const visited = new Set<string>();
  const visit = (declaration: StructDeclaration): void => {
    if (visited.has(declaration.name)) return;
    visited.add(declaration.name);
    for (const field of declaration.fields) {
      const nested = structs.get(field.type.name);
      if (nested) visit(nested);
    }
    result.push(declaration);
  };
  for (const declaration of declarations) visit(declaration);
  return result;
}
